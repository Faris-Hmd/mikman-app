import React, { useState, useEffect, useMemo } from 'react';
import { Layers, Clock, HardDrive, DollarSign, X, ChevronDown, AlertCircle, Loader2, Trash2 } from 'lucide-react';
import { useLanguage } from '../../context/LanguageContext';
import { Profile } from './types';

export interface ProfileSavePayload {
  isEdit: boolean;
  profileId?: string;
  name: string;
  price?: number;
  validity: string;
  limitMB?: number;
  isUnlimited: boolean;
}

interface ProfileDrawerProps {
  isOpen: boolean;
  onClose: () => void;
  editingProfile: Profile | null;
  onSaveProfile: (payload: ProfileSavePayload) => Promise<void>;
  onDeleteRequest?: (profile: Profile) => void;
}

const parseValidity = (str?: string) => {
  if (!str) return { num: 0, unit: '', isUnl: true };
  const s = str.trim().toLowerCase();
  if (s === '0d' || s === '0h' || s === '0m' || s === '0' || s === 'unlimited' || s === 'none' || s === 'infinity' || s === '∞') {
    return { num: 0, unit: '', isUnl: true };
  }
  const match = s.match(/^(\d+)\s*([a-zA-Z]+)?$/);
  if (match) {
    const num = parseInt(match[1], 10) || 1;
    if (num === 0) return { num: 0, unit: '', isUnl: true };
    const u = (match[2] || 'd').toLowerCase();
    const unit = ['m', 'h', 'd', 'w'].includes(u) ? u : 'd';
    return { num, unit, isUnl: false };
  }
  return { num: 0, unit: '', isUnl: true };
};

const toArabicDigits = (val: number | string): string => {
  const arabicDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return String(val).replace(/[0-9]/g, (d) => arabicDigits[Number(d)]);
};

const generateDefaultProfileName = (
  isUnlimitedTime: boolean,
  validityNum: number | string,
  validityUnit: string,
  isUnlimitedData: boolean,
  limitMB: number | undefined,
  customVal: number | string,
  customUnit: 'MB' | 'GB',
  isArabic: boolean
): string => {
  let timeStr = '';
  if (isUnlimitedTime) {
    timeStr = isArabic ? 'بدون حد' : 'Unlimited';
  } else {
    const rawNum = validityNum !== '' && !isNaN(Number(validityNum)) ? Number(validityNum) : '';
    const unit = (validityUnit || 'd').toLowerCase();
    if (isArabic) {
      if (rawNum === '') {
        timeStr = '';
      } else {
        const n = Number(rawNum);
        let unitLabel = 'يوم';
        if (unit === 'm') unitLabel = n >= 3 && n <= 10 ? 'دقائق' : 'دقيقة';
        if (unit === 'h') unitLabel = n >= 3 && n <= 10 ? 'ساعات' : 'ساعة';
        if (unit === 'd') unitLabel = n >= 3 && n <= 10 ? 'أيام' : 'يوم';
        if (unit === 'w') unitLabel = n >= 3 && n <= 10 ? 'أسابيع' : 'أسبوع';
        timeStr = `${toArabicDigits(rawNum)} ${unitLabel}`;
      }
    } else {
      if (rawNum === '') {
        timeStr = '';
      } else {
        let unitLabel = 'D';
        if (unit === 'm') unitLabel = 'M';
        if (unit === 'h') unitLabel = 'H';
        if (unit === 'd') unitLabel = 'D';
        if (unit === 'w') unitLabel = 'W';
        timeStr = `${rawNum}${unitLabel}`;
      }
    }
  }

  let dataStr = '';
  if (!isUnlimitedData) {
    if (customVal !== '' && !isNaN(Number(customVal)) && Number(customVal) > 0) {
      if (isArabic) {
        const unitLabel = customUnit === 'GB' ? 'جيجا' : 'ميجا';
        dataStr = `${toArabicDigits(customVal)} ${unitLabel}`;
      } else {
        dataStr = `${customVal}${customUnit}`;
      }
    } else if (limitMB && limitMB > 0) {
      if (limitMB >= 1024 && limitMB % 1024 === 0) {
        const gb = limitMB / 1024;
        dataStr = isArabic ? `${toArabicDigits(gb)} جيجا` : `${gb}GB`;
      } else {
        dataStr = isArabic ? `${toArabicDigits(limitMB)} ميجا` : `${limitMB}MB`;
      }
    }
  }

  if (timeStr && dataStr) {
    if (isUnlimitedTime && dataStr) return dataStr;
    return `${timeStr} ${dataStr}`;
  }
  if (timeStr) return timeStr;
  if (dataStr) return dataStr;
  return isArabic ? 'بروفايل جديد' : 'New Profile';
};

export const ProfileDrawer: React.FC<ProfileDrawerProps> = ({
  isOpen,
  onClose,
  editingProfile,
  onSaveProfile,
  onDeleteRequest,
}) => {
  const { t, isRtl } = useLanguage();

  const [name, setName] = useState('');
  const [isNameAutoGenerated, setIsNameAutoGenerated] = useState(true);
  const [validityNum, setValidityNum] = useState<number | string>(1);
  const [validityUnit, setValidityUnit] = useState<string>('d');
  const [isUnlimitedTime, setIsUnlimitedTime] = useState(false);

  const [limitMB, setLimitMB] = useState<number | undefined>(undefined);
  const [isUnlimited, setIsUnlimited] = useState(true);
  const [customVal, setCustomVal] = useState<number | string>('');
  const [customUnit, setCustomUnit] = useState<'MB' | 'GB'>('GB');
  const [revenue, setRevenue] = useState<string | number>('');

  const [isSubmitting, setIsSubmitting] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');

  // Presets
  const validityPresets = useMemo(() => [
    { label: t('profiles.unlimitedTime'), num: 0, unit: '', isUnl: true },
    { label: `${isRtl ? toArabicDigits(1) : 1} ${t('profiles.unitHours')}`, num: 1, unit: 'h', isUnl: false },
    { label: `${isRtl ? toArabicDigits(12) : 12} ${t('profiles.unitHours')}`, num: 12, unit: 'h', isUnl: false },
    { label: `${isRtl ? toArabicDigits(1) : 1} ${t('profiles.unitDays')}`, num: 1, unit: 'd', isUnl: false },
    { label: `${isRtl ? toArabicDigits(7) : 7} ${t('profiles.unitDays')}`, num: 7, unit: 'd', isUnl: false },
    { label: `${isRtl ? toArabicDigits(30) : 30} ${t('profiles.unitDays')}`, num: 30, unit: 'd', isUnl: false },
  ], [t, isRtl]);

  const dataPresets = useMemo(() => [
    { label: t('profiles.unlimited'), mb: 0, val: '', unit: 'GB' as const, isUnl: true },
    { label: '500 MB', mb: 500, val: 500, unit: 'MB' as const, isUnl: false },
    { label: '1 GB', mb: 1024, val: 1, unit: 'GB' as const, isUnl: false },
    { label: '2 GB', mb: 2048, val: 2, unit: 'GB' as const, isUnl: false },
    { label: '5 GB', mb: 5120, val: 5, unit: 'GB' as const, isUnl: false },
  ], [t]);

  // Sync state when opening or switching profile
  useEffect(() => {
    if (!isOpen) return;

    setErrorMsg('');
    if (editingProfile) {
      setName(editingProfile.name || '');
      setIsNameAutoGenerated(false);

      const { num, unit, isUnl } = parseValidity(editingProfile.validity);
      setIsUnlimitedTime(isUnl);
      setValidityNum(isUnl ? 1 : num);
      setValidityUnit(isUnl ? 'd' : unit);

      const profileIsUnl = editingProfile.isUnlimited ?? !editingProfile.limitMB;
      setIsUnlimited(profileIsUnl);
      setLimitMB(editingProfile.limitMB);

      if (!profileIsUnl && editingProfile.limitMB) {
        if (editingProfile.limitMB % 1024 === 0) {
          setCustomUnit('GB');
          setCustomVal(editingProfile.limitMB / 1024);
        } else {
          setCustomUnit('MB');
          setCustomVal(editingProfile.limitMB);
        }
      } else {
        setCustomVal('');
        setCustomUnit('GB');
      }

      const initialRev = editingProfile.revenue != null ? editingProfile.revenue : editingProfile.price != null ? editingProfile.price : '';
      setRevenue(initialRev !== '' ? String(initialRev) : '');
    } else {
      setIsNameAutoGenerated(true);
      const initialName = generateDefaultProfileName(false, 1, 'd', true, undefined, '', 'GB', isRtl);
      setName(initialName);
      setValidityNum(1);
      setValidityUnit('d');
      setIsUnlimitedTime(false);
      setLimitMB(undefined);
      setIsUnlimited(true);
      setCustomVal('');
      setCustomUnit('GB');
      setRevenue('');
    }
  }, [isOpen, editingProfile, isRtl]);

  const updateAutoNameIfNeeded = (
    unlTime = isUnlimitedTime,
    vNum: number | string = validityNum,
    vUnit = validityUnit,
    unlData = isUnlimited,
    lMB = limitMB,
    cVal = customVal,
    cUnit = customUnit
  ) => {
    if (!editingProfile && isNameAutoGenerated) {
      const newAutoName = generateDefaultProfileName(
        unlTime,
        vNum,
        vUnit,
        unlData,
        lMB,
        cVal,
        cUnit,
        isRtl
      );
      setName(newAutoName);
    }
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!name.trim()) return;

    setIsSubmitting(true);
    setErrorMsg('');

    const effectiveValidityNum = Number(validityNum) >= 1 ? Number(validityNum) : 1;
    const formattedValidity = isUnlimitedTime ? '0d' : `${effectiveValidityNum}${validityUnit || 'd'}`;
    const apiIsUnlimited = isUnlimitedTime && isUnlimited;

    const effectiveLimitMB = isUnlimited
      ? undefined
      : customVal !== '' && !isNaN(Number(customVal)) && Number(customVal) > 0
      ? customUnit === 'GB'
        ? Math.round(Number(customVal) * 1024)
        : Math.round(Number(customVal))
      : limitMB
      ? Number(limitMB)
      : undefined;

    try {
      await onSaveProfile({
        isEdit: !!editingProfile,
        profileId: editingProfile?.['.id'],
        name: name.trim(),
        price: revenue ? Number(revenue) : undefined,
        validity: formattedValidity,
        limitMB: effectiveLimitMB,
        isUnlimited: apiIsUnlimited,
      });

      onClose();
    } catch (err: any) {
      setErrorMsg(err?.message || (editingProfile ? t('profiles.couldNotUpdate') : t('profiles.couldNotCreate')));
    } finally {
      setIsSubmitting(false);
    }
  };

  if (!isOpen) return null;

  return (
    <div
      className="create-batch-drawer-overlay"
      dir={isRtl ? 'rtl' : 'ltr'}
      onClick={() => {
        if (!isSubmitting) onClose();
      }}
    >
      <div
        className="create-batch-drawer-content"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="sheet-drag-handle" />

        {/* Header */}
        <div className="profile-drawer-header">
          <div className="profile-drawer-header-left">
            <div className="profile-drawer-icon">
              <Layers size={16} />
            </div>
            <h3 className="profile-drawer-title">
              {editingProfile ? t('profiles.editProfileTitle') : t('profiles.createProfileTitle')}
            </h3>
          </div>
          <button
            type="button"
            className="profile-drawer-close"
            onClick={onClose}
            disabled={isSubmitting}
          >
            <X size={16} />
          </button>
        </div>

        {/* Body Form */}
        <form onSubmit={handleSubmit} className="profile-drawer-form">
          <div className="profile-drawer-body">
            {errorMsg && (
              <div className="profile-form-error">
                <AlertCircle size={15} />
                <span>{errorMsg}</span>
              </div>
            )}

            {/* Profile Name */}
            <div className="profile-form-group">
              <label className="profile-form-label">
                {t('profiles.nameLabel')} *
              </label>
              <div className="profile-input-wrapper">
                <Layers size={14} className="profile-embedded-icon" />
                <input
                  type="text"
                  required
                  value={name}
                  onChange={(e) => {
                    setIsNameAutoGenerated(false);
                    setName(e.target.value);
                  }}
                  placeholder={t('profiles.namePlaceholder')}
                  className="profile-input"
                />
              </div>
            </div>

            {/* Validity Duration */}
            <div className="profile-form-group">
              <div className="profile-form-header-row">
                <label className="profile-form-label">
                  {t('profiles.validityLabel')} *
                </label>
                <span className="profile-form-value-badge">
                  {isUnlimitedTime
                    ? t('profiles.unlimitedTime')
                    : `${validityNum} ${
                        validityUnit === 'm'
                          ? t('profiles.unitMinutes')
                          : validityUnit === 'h'
                          ? t('profiles.unitHours')
                          : validityUnit === 'd'
                          ? t('profiles.unitDays')
                          : t('profiles.unitWeeks')
                      }`}
                </span>
              </div>

              {/* Validity Presets Grid */}
              <div className="profile-preset-grid validity">
                {validityPresets.map((vp) => {
                  const isSelected = vp.isUnl
                    ? isUnlimitedTime
                    : !isUnlimitedTime && Number(validityNum) === vp.num && validityUnit === vp.unit;
                  return (
                    <button
                      key={vp.label}
                      type="button"
                      className={`profile-preset-btn ${isSelected ? 'active' : ''}`}
                      onClick={() => {
                        if (vp.isUnl) {
                          setIsUnlimitedTime(true);
                          updateAutoNameIfNeeded(true, validityNum, validityUnit, isUnlimited, limitMB, customVal, customUnit);
                        } else {
                          setIsUnlimitedTime(false);
                          setValidityNum(vp.num);
                          setValidityUnit(vp.unit);
                          updateAutoNameIfNeeded(false, vp.num, vp.unit, isUnlimited, limitMB, customVal, customUnit);
                        }
                      }}
                    >
                      {vp.label}
                    </button>
                  );
                })}
              </div>

              {/* Direct Numeric Input + Unit Select Dropdown */}
              {!isUnlimitedTime && (
                <div className="profile-input-row">
                  <div className="profile-input-wrapper flex-1">
                    <Clock size={14} className="profile-embedded-icon" />
                    <input
                      type="number"
                      min="1"
                      required={!isUnlimitedTime}
                      value={validityNum}
                      onChange={(e) => {
                        const val = e.target.value;
                        const normalized = val.replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)));
                        setValidityNum(normalized);
                        const parsed = normalized !== '' && !isNaN(Number(normalized)) ? Number(normalized) : '';
                        updateAutoNameIfNeeded(isUnlimitedTime, parsed, validityUnit, isUnlimited, limitMB, customVal, customUnit);
                      }}
                      onBlur={() => {
                        if (validityNum === '' || Number(validityNum) < 1) {
                          setValidityNum(1);
                          updateAutoNameIfNeeded(isUnlimitedTime, 1, validityUnit, isUnlimited, limitMB, customVal, customUnit);
                        }
                      }}
                      placeholder={t('profiles.validityPlaceholder')}
                      className="profile-input"
                    />
                  </div>
                  <div className="profile-select-wrapper validity-unit">
                    <select
                      value={validityUnit}
                      onChange={(e) => {
                        const u = e.target.value;
                        setValidityUnit(u);
                        updateAutoNameIfNeeded(isUnlimitedTime, validityNum, u, isUnlimited, limitMB, customVal, customUnit);
                      }}
                      className="profile-select"
                    >
                      <option value="m">{t('profiles.unitMinutes')}</option>
                      <option value="h">{t('profiles.unitHours')}</option>
                      <option value="d">{t('profiles.unitDays')}</option>
                      <option value="w">{t('profiles.unitWeeks')}</option>
                    </select>
                    <ChevronDown size={14} className="profile-select-chevron" />
                  </div>
                </div>
              )}
            </div>

            {/* Data Limit Control */}
            <div className="profile-form-group">
              <div className="profile-form-header-row">
                <label className="profile-form-label">
                  <HardDrive size={14} />
                  <span>{t('profiles.limitDataTraffic')}</span>
                </label>
                <span className="profile-form-value-badge">
                  {isUnlimited
                    ? t('profiles.unlimited')
                    : `${customVal || (limitMB ? (limitMB >= 1024 ? limitMB / 1024 : limitMB) : '')} ${customUnit}`}
                </span>
              </div>

              {/* Data Presets Grid */}
              <div className="profile-preset-grid data">
                {dataPresets.map((dp) => {
                  const isSelected = dp.isUnl ? isUnlimited : !isUnlimited && limitMB === dp.mb;
                  return (
                    <button
                      key={dp.label}
                      type="button"
                      className={`profile-preset-btn ${isSelected ? 'active' : ''}`}
                      onClick={() => {
                        if (dp.isUnl) {
                          setIsUnlimited(true);
                          setLimitMB(undefined);
                          setCustomVal('');
                          updateAutoNameIfNeeded(isUnlimitedTime, validityNum, validityUnit, true, undefined, '', customUnit);
                        } else {
                          setIsUnlimited(false);
                          setLimitMB(dp.mb);
                          setCustomVal(dp.val);
                          setCustomUnit(dp.unit);
                          updateAutoNameIfNeeded(isUnlimitedTime, validityNum, validityUnit, false, dp.mb, dp.val, dp.unit);
                        }
                      }}
                    >
                      {dp.label}
                    </button>
                  );
                })}
              </div>

              {/* Numeric Data Input */}
              <div className="profile-input-row">
                <div className="profile-input-wrapper flex-1">
                  <HardDrive size={14} className="profile-embedded-icon" />
                  <input
                    type="number"
                    step="any"
                    min="0.1"
                    value={customVal}
                    onChange={(e) => {
                      const val = e.target.value;
                      const normalized = val.replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)));
                      if (normalized === '') {
                        setCustomVal('');
                        setLimitMB(undefined);
                        setIsUnlimited(true);
                        updateAutoNameIfNeeded(isUnlimitedTime, validityNum, validityUnit, true, undefined, '', customUnit);
                      } else {
                        const num = parseFloat(normalized);
                        setCustomVal(normalized);
                        if (!isNaN(num) && num > 0) {
                          const calculatedMB = customUnit === 'GB' ? Math.round(num * 1024) : Math.round(num);
                          setIsUnlimited(false);
                          setLimitMB(calculatedMB);
                          updateAutoNameIfNeeded(isUnlimitedTime, validityNum, validityUnit, false, calculatedMB, normalized, customUnit);
                        } else {
                          setLimitMB(undefined);
                        }
                      }
                    }}
                    placeholder={isUnlimited ? t('profiles.unlimited') : t('profiles.specificLimit')}
                    className="profile-input"
                  />
                </div>
                <div className="profile-select-wrapper data-unit">
                  <select
                    value={customUnit}
                    onChange={(e) => {
                      const u = e.target.value as 'MB' | 'GB';
                      setCustomUnit(u);
                      if (customVal !== '' && !isNaN(Number(customVal)) && Number(customVal) > 0) {
                        const calculatedMB = u === 'GB' ? Math.round(Number(customVal) * 1024) : Math.round(Number(customVal));
                        setIsUnlimited(false);
                        setLimitMB(calculatedMB);
                        updateAutoNameIfNeeded(isUnlimitedTime, validityNum, validityUnit, false, calculatedMB, customVal, u);
                      }
                    }}
                    className="profile-select"
                  >
                    <option value="GB">GB</option>
                    <option value="MB">MB</option>
                  </select>
                  <ChevronDown size={14} className="profile-select-chevron" />
                </div>
              </div>
            </div>

            {/* Price Field */}
            <div className="profile-form-group">
              <label className="profile-form-label">
                {t('profiles.priceLabel')}
              </label>
              <div className="profile-input-wrapper">
                <DollarSign size={14} className="profile-embedded-icon" />
                <input
                  type="number"
                  step="0.01"
                  min="0"
                  value={revenue}
                  onChange={(e) => setRevenue(e.target.value)}
                  placeholder="0.00"
                  className="profile-input"
                />
              </div>
            </div>
          </div>

          {/* Sticky Drawer Footer */}
          <div className="profile-drawer-footer">
            {editingProfile && onDeleteRequest ? (
              <button
                type="button"
                className="profile-btn profile-btn-danger"
                onClick={() => {
                  onClose();
                  onDeleteRequest(editingProfile);
                }}
                disabled={isSubmitting}
              >
                <Trash2 size={14} />
                <span>{t('profiles.deleteBtn')}</span>
              </button>
            ) : <div />}

            <div className="profile-drawer-footer-actions">
              <button
                type="button"
                className="profile-btn profile-btn-secondary"
                onClick={onClose}
                disabled={isSubmitting}
              >
                {t('profiles.cancelBtn')}
              </button>
              <button
                type="submit"
                className="profile-btn profile-btn-primary"
                disabled={isSubmitting}
              >
                {isSubmitting ? (
                  <>
                    <Loader2 size={14} className="animate-spin" />
                    <span>{t('profiles.saving')}</span>
                  </>
                ) : (
                  <span>{editingProfile ? t('profiles.updateBtn') : t('profiles.saveBtn')}</span>
                )}
              </button>
            </div>
          </div>
        </form>
      </div>
    </div>
  );
};
