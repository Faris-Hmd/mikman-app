const parseValidity = (str?: string) => {
  if (!str) {
    return { num: 1, unit: 'd', isUnl: false };
  }
  const s = str.trim().toLowerCase();
  if (s === '0d' || s === '0h' || s === '0m' || s === '0' || s === 'unlimited' || s === 'none') {
    return { num: 0, unit: '', isUnl: true };
  }
  const match = s.match(/^(\d+)\s*([a-zA-Z]+)?$/);
  if (match) {
    const num = parseInt(match[1], 10) || 1;
    if (num === 0) {
      return { num: 0, unit: '', isUnl: true };
    }
    const u = (match[2] || 'd').toLowerCase();
    const unit = ['m', 'h', 'd', 'w'].includes(u) ? u : 'd';
    return { num, unit, isUnl: false };
  }
  return { num: 1, unit: 'd', isUnl: false };
};

const formatPriceBadge = (val: number): string => {
  if (val >= 1000) {
    const kVal = val / 1000;
    const formatted = kVal % 1 === 0 ? String(kVal) : kVal.toFixed(1).replace(/\.0$/, '');
    return `${formatted}k`;
  }
  if (val % 1 === 0) {
    return String(val);
  }
  return String(Number(val.toFixed(2)));
};

const generateDefaultProfileName = (
  isUnlimitedTime: boolean,
  validityNum: number,
  validityUnit: string,
  isUnlimitedData: boolean,
  limitMB: number | undefined,
  isCustomLimit: boolean,
  customVal: number | string,
  customUnit: 'MB' | 'GB',
  isArabic: boolean
): string => {
  let timeStr = '';
  if (isUnlimitedTime) {
    timeStr = isArabic ? 'بدون حد' : 'Unlimited';
  } else {
    const num = validityNum || 1;
    const unit = (validityUnit || 'd').toLowerCase();
    if (isArabic) {
      let unitLabel = 'يوم';
      if (unit === 'm') unitLabel = num >= 3 && num <= 10 ? 'دقائق' : 'دقيقة';
      if (unit === 'h') unitLabel = num >= 3 && num <= 10 ? 'ساعات' : 'ساعة';
      if (unit === 'd') unitLabel = num >= 3 && num <= 10 ? 'أيام' : 'يوم';
      if (unit === 'w') unitLabel = num >= 3 && num <= 10 ? 'أسابيع' : 'أسبوع';
      timeStr = `${num} ${unitLabel}`;
    } else {
      let unitLabel = 'D';
      if (unit === 'm') unitLabel = 'M';
      if (unit === 'h') unitLabel = 'H';
      if (unit === 'd') unitLabel = 'D';
      if (unit === 'w') unitLabel = 'W';
      timeStr = `${num}${unitLabel}`;
    }
  }

  let dataStr = '';
  if (!isUnlimitedData) {
    let effectiveMB: number | undefined = undefined;
    if (isCustomLimit) {
      if (customVal !== '' && !isNaN(Number(customVal))) {
        effectiveMB = customUnit === 'GB' ? Number(customVal) * 1024 : Number(customVal);
      }
    } else if (limitMB) {
      effectiveMB = limitMB;
    }

    if (effectiveMB && effectiveMB > 0) {
      if (effectiveMB >= 1024 && effectiveMB % 1024 === 0) {
        const gb = effectiveMB / 1024;
        dataStr = isArabic ? `${gb} جيجا` : `${gb}GB`;
      } else {
        dataStr = isArabic ? `${effectiveMB} ميجا` : `${effectiveMB}MB`;
      }
    }
  }

  if (timeStr && dataStr) {
    if (isUnlimitedTime && dataStr) {
      return dataStr;
    }
    return `${timeStr} ${dataStr}`;
  }
  if (timeStr) {
    return timeStr;
  }
  if (dataStr) {
    return dataStr;
  }
  return isArabic ? 'بروفايل جديد' : 'New Profile';
};

